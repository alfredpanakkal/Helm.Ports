const warned = new Set<string>();

/**
 * Look up the ISO 3166-1 alpha-2 code for a canonical country name.
 * Returns null for unknown names and logs each unknown name once so new
 * entries are easy to spot and add to the table above.
 */
export function getCountryIso2(name: string): string | null {
  const cc = COUNTRY_ISO2[name];
  if (cc) return cc;
  if (name && !warned.has(name)) {
    warned.add(name);
    console.warn("[countryCodes] No ISO2 code for country: " + name);
  }
  return null;
}
